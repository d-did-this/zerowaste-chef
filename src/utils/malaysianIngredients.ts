/**
 * Quick search / autocomplete function
 */
export function searchIngredients(query: string): LocalIngredient[] {
  if (!query || query.trim() === "") return MALAYSIAN_INGREDIENTS_DB;
  const q = query.toLowerCase().trim();

  return MALAYSIAN_INGREDIENTS_DB.filter(
    (item) =>
      item.name.toLowerCase().includes(q) ||
      item.nameMalay.toLowerCase().includes(q) ||
      item.keywords.some((kw) => kw.includes(q))
  );
}

/**
 * Match a raw string prediction to the Malaysian DB
 */
export function findMatchingMalaysianIngredient(rawText: string): LocalIngredient | null {
  if (!rawText) return null;
  const lower = rawText.toLowerCase().trim();

  // 1. Direct or keyword match
  for (const item of MALAYSIAN_INGREDIENTS_DB) {
    if (
      lower.includes(item.name.toLowerCase()) ||
      lower.includes(item.nameMalay.toLowerCase()) ||
      item.keywords.some((kw) => lower.includes(kw))
    ) {
      return item;
    }
  }

  return null;
}
